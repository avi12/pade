/// Each file's parse, kept until the file is written again: a project is
/// re-listed about once a second while an agent works.
static CLAUDE_TITLES: LazyLock<ParsedFiles<Option<String>>> = LazyLock::new(ParsedFiles::default);
static CODEX_SESSIONS: LazyLock<ParsedFiles<Option<InteractiveSession>>> =
    LazyLock::new(ParsedFiles::default);
static COPILOT_WORKSPACES: LazyLock<ParsedFiles<Option<CopilotWorkspace>>> =
    LazyLock::new(ParsedFiles::default);

/// The most conversations listed for one project, newest first - `/resume`
/// pages its own list the same way.
const MAXIMUM_CONVERSATIONS: usize = 50;
/// How many of the newest files of each agent are inspected, so a long history
/// never turns one listing into a full scan.
const NEWEST_FILES_INSPECTED: usize = 256;
/// How much of a Claude transcript's end is read for its title records.
const TRANSCRIPT_TAIL_BYTES: u64 = 64 * 1024;
/// How much of a Claude transcript's start is read for its first prompt.
const TRANSCRIPT_HEAD_BYTES: u64 = 256 * 1024;
pub(super) const TRANSCRIPT_EXTENSION: &str = "jsonl";
const CUSTOM_TITLE_RECORD: &str = "custom-title";
const AI_TITLE_RECORD: &str = "ai-title";
const USER_RECORD: &str = "user";
/// Claude's `entrypoint` for a headless `claude -p` run (PADE's own naming
/// asks it this way), which `/resume` doesn't offer either.
const HEADLESS_ENTRYPOINT_PREFIX: &str = "sdk";
/// The flags Claude sets on a user record it wrote itself - an expanded skill
/// or slash command, an image's source note, a classifier notice, the summary
/// a compaction carries over.
const SYNTHETIC_RECORD_FLAGS: [&str; 3] =
    ["isMeta", "isCompactSummary", "isVisibleInTranscriptOnly"];
/// How the text of an unflagged user record Claude wrote itself begins: a
/// local command's caveat and output, a `!` command's output, a background
/// task's notice, an injected reminder, a hook's echo, an interruption marker
/// and the older, untagged caveat and compaction summary.
const SYNTHETIC_PROMPT_MARKERS: [&str; 12] = [
    "<local-command-caveat>",
    "<local-command-stdout>",
    "<local-command-stderr>",
    "<command-message>",
    "<bash-stdout>",
    "<bash-stderr>",
    "<task-notification>",
    "<system-reminder>",
    "<user-prompt-submit-hook>",
    "[Request interrupted by user",
    "Caveat: The messages below were generated by the user while running local commands",
    "This session is being continued from a previous conversation",
];
const COMMAND_NAME_TAG: &str = "command-name";
const COMMAND_ARGUMENTS_TAG: &str = "command-args";
const SHELL_INPUT_TAG: &str = "bash-input";
/// How `/resume`-style lists show a `!` shell command the person ran.
const SHELL_COMMAND_PREFIX: &str = "!";
/// The wrapper Claude records a paste in; its text is the person's own.
const PASTED_CONTENT_TAG: &str = "pasted_content";
const TEXT_PART: &str = "text";
const TOOL_RESULT_PART: &str = "tool_result";
pub(super) const CODEX_SESSION_INDEX: &str = "session_index.jsonl";
pub(super) const COPILOT_WORKSPACE_FILE: &str = "workspace.yaml";
const COPILOT_CWD_KEY: &str = "cwd:";
const COPILOT_SUMMARY_KEY: &str = "summary:";
/// The indicators of a YAML block scalar (`summary: |-`), whose value is on
/// the indented lines below.
const YAML_BLOCK_SCALAR_INDICATORS: [char; 2] = ['|', '>'];
const MARKDOWN_HEADING_MARK: char = '#';

/// One recorded conversation, as the sidebar lists and reopens it.
#[derive(Debug, Clone, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct RecordedConversation {
    agent_id: &'static str,
    /// The agent's own id for the conversation.
    conversation_id: String,
    title: Option<String>,
    /// Milliseconds since the Unix epoch.
    updated_at: u64,
    /// The launch arguments that reopen it, for an agent that isn't pinned by
    /// `conversation_id` at spawn.
    resume_arguments: Vec<String>,
}

/// `project`'s recorded conversations, newest first.
// `async` plus `spawn_blocking`: it reads many files, which must stay off the
// main thread.
#[tauri::command]
pub async fn agent_conversations(project: String) -> Vec<RecordedConversation> {
    remember_listed_project(&project);
    tauri::async_runtime::spawn_blocking(move || project_conversations(&project))
        .await
        .unwrap_or_default()
}

fn project_conversations(project: &str) -> Vec<RecordedConversation> {
    let mut conversations = claude_conversations(project);
    conversations.extend(codex_conversations(project));
    conversations.extend(copilot_conversations(project));
    conversations.sort_by_key(|conversation| std::cmp::Reverse(conversation.updated_at));
    conversations.truncate(MAXIMUM_CONVERSATIONS);
    conversations
}

/// The newest entries first, bounded to the ones worth inspecting.
fn newest<T>(mut entries: Vec<(SystemTime, T)>) -> impl Iterator<Item = (SystemTime, T)> {
    entries.sort_by_key(|(modified, _)| std::cmp::Reverse(*modified));
    entries.into_iter().take(NEWEST_FILES_INSPECTED)
}

fn modified_time(path: &Path) -> Option<SystemTime> {
    path.metadata()
        .and_then(|metadata| metadata.modified())
        .ok()
}

/// A directory entry's modified time as the listing itself reports it - on
/// Windows that costs nothing, where [`modified_time`] opens the file.
fn listed_modified_time(entry: &DirEntry) -> Option<SystemTime> {
    entry
        .metadata()
        .and_then(|metadata| metadata.modified())
        .ok()
}

/// The list title a Claude transcript earns, `None` for one that isn't a
/// conversation to resume (see [`first_typed_prompt`]).
pub(super) fn claude_transcript_title(path: &Path) -> Option<String> {
    let first_prompt = first_typed_prompt(path)?;
    Some(transcript_title(path).unwrap_or(first_prompt))
}

fn claude_conversations(project: &str) -> Vec<RecordedConversation> {
    let Some(projects) = claude_projects_directory() else {
        return Vec::new();
    };
    let Ok(entries) = std::fs::read_dir(projects.join(encode_project(project))) else {
        return Vec::new();
    };
    let transcripts = entries
        .flatten()
        .filter(|entry| {
            Path::new(&entry.file_name())
                .extension()
                .is_some_and(|extension| extension == TRANSCRIPT_EXTENSION)
        })
        .filter_map(|entry| Some((listed_modified_time(&entry)?, entry.path())))
        .collect();

    newest(transcripts)
        .filter_map(|(modified, path)| {
            let conversation_id = path.file_stem()?.to_str()?.to_string();
            let title = CLAUDE_TITLES.get_or_parse(&path, modified, claude_transcript_title)?;
            Some(RecordedConversation {
                agent_id: ID_CLAUDE,
                conversation_id,
                title: Some(title),
                updated_at: milliseconds_since_unix_epoch(modified),
                resume_arguments: Vec::new(),
            })
        })
        .collect()
}

/// The JSON records of a transcript's lines, skipping any that don't parse (a
/// line cut by a bounded read).
fn records(reader: impl BufRead) -> impl Iterator<Item = serde_json::Value> {
    reader
        .lines()
        .map_while(Result::ok)
        .filter_map(|line| serde_json::from_str(&line).ok())
}

fn record_type(record: &serde_json::Value) -> Option<&str> {
    record.get("type")?.as_str()
}

/// The newest `/rename` title, else Claude's own generated one.
fn transcript_title(path: &Path) -> Option<String> {
    let mut file = File::open(path).ok()?;
    let length = file.metadata().ok()?.len();
    file.seek(SeekFrom::Start(
        length.saturating_sub(TRANSCRIPT_TAIL_BYTES),
    ))
    .ok()?;
    let mut custom_title = None;
    let mut ai_title = None;
    for record in records(BufReader::new(file)) {
        match record_type(&record) {
            Some(CUSTOM_TITLE_RECORD) => custom_title = string_field(&record, "customTitle"),
            Some(AI_TITLE_RECORD) => ai_title = string_field(&record, "aiTitle"),
            _ => {}
        }
    }
    custom_title.or(ai_title)
}

fn string_field(record: &serde_json::Value, key: &str) -> Option<String> {
    let value = record.get(key)?.as_str()?.trim();
    (!value.is_empty()).then(|| value.to_string())
}

/// What one user record of a transcript holds, once Claude's own are set aside.
#[derive(Debug, PartialEq, Eq)]
enum UserTurn {
    /// A prompt the person typed (or pasted).
    Typed(String),
    /// A slash or `!` shell command the person ran, as they typed it.
    Command(String),
}

/// The first prompt the person typed into the conversation, else the first
/// command they ran: a `/model` or `/effort` up front says nothing about what
/// the conversation is about, so it titles only a transcript with no prompt.
/// `None` for a transcript with neither, or one a headless run recorded -
/// neither is a conversation to resume.
fn first_typed_prompt(path: &Path) -> Option<String> {
    let head = File::open(path).ok()?.take(TRANSCRIPT_HEAD_BYTES);
    let mut user_records = records(BufReader::new(head))
        .filter(|record| record_type(record) == Some(USER_RECORD))
        .peekable();
    let is_headless = user_records
        .peek()?
        .get("entrypoint")
        .and_then(serde_json::Value::as_str)
        .is_some_and(|entrypoint| entrypoint.starts_with(HEADLESS_ENTRYPOINT_PREFIX));
    if is_headless {
        return None;
    }

    let mut first_command = None;
    for turn in user_records.filter_map(|record| user_turn(&record)) {
        match turn {
            UserTurn::Typed(prompt) => return Some(prompt),
            UserTurn::Command(command) => {
                first_command.get_or_insert(command);
            }
        }
    }
    first_command
}

/// What the person put into one user record, `None` for a record Claude wrote
/// itself (see [`SYNTHETIC_RECORD_FLAGS`] and [`SYNTHETIC_PROMPT_MARKERS`]) or
/// one carrying a tool's result.
fn user_turn(record: &serde_json::Value) -> Option<UserTurn> {
    let is_synthetic_record = SYNTHETIC_RECORD_FLAGS
        .iter()
        .any(|flag| record.get(flag).and_then(serde_json::Value::as_bool) == Some(true));
    if is_synthetic_record {
        return None;
    }

    let text = typed_text(record.get("message")?.get("content")?)?;
    let is_tagged = text.starts_with('<');
    if is_tagged {
        if let Some(name) = tag_content(text, COMMAND_NAME_TAG) {
            let arguments = tag_content(text, COMMAND_ARGUMENTS_TAG).unwrap_or_default();
            return Some(UserTurn::Command(
                format!("{name} {arguments}").trim_end().to_string(),
            ));
        }
        if let Some(command) = tag_content(text, SHELL_INPUT_TAG) {
            return Some(UserTurn::Command(format!(
                "{SHELL_COMMAND_PREFIX}{command}"
            )));
        }
    }
    let is_synthetic_text = SYNTHETIC_PROMPT_MARKERS
        .iter()
        .any(|marker| text.starts_with(marker));
    if is_synthetic_text {
        return None;
    }

    let prompt = without_tag(text, PASTED_CONTENT_TAG);
    let trimmed = prompt.trim();
    (!trimmed.is_empty()).then(|| UserTurn::Typed(trimmed.to_string()))
}

/// A user message's text, trimmed: the string itself, or the first text part
/// of a part list. `None` for a list carrying a tool's result, which Claude
/// records as a user turn.
fn typed_text(content: &serde_json::Value) -> Option<&str> {
    if let Some(text) = content.as_str() {
        return Some(text.trim());
    }

    let parts = content.as_array()?;
    let is_tool_result = parts
        .iter()
        .any(|part| record_type(part) == Some(TOOL_RESULT_PART));
    if is_tool_result {
        return None;
    }
    parts
        .iter()
        .filter(|part| record_type(part) == Some(TEXT_PART))
        .find_map(|part| part.get(TEXT_PART)?.as_str())
        .map(str::trim)
}

/// The trimmed, non-empty text between `<tag>` and `</tag>`.
fn tag_content<'text>(text: &'text str, tag: &str) -> Option<&'text str> {
    let opening = format!("<{tag}>");
    let closing = format!("</{tag}>");
    let start = text.find(&opening)? + opening.len();
    let length = text[start..].find(&closing)?;
    let content = text[start..start + length].trim();
    (!content.is_empty()).then_some(content)
}

/// `text` with every opening and closing `tag` dropped, attributes and all,
/// and what they wrapped kept.
fn without_tag(text: &str, tag: &str) -> String {
    let opening = format!("<{tag}");
    let closing = format!("</{tag}");
    let mut kept = String::with_capacity(text.len());
    let mut remaining = text;
    loop {
        let next_tag = [remaining.find(&opening), remaining.find(&closing)]
            .into_iter()
            .flatten()
            .min();
        let Some(start) = next_tag else {
            kept.push_str(remaining);
            return kept;
        };
        kept.push_str(&remaining[..start]);
        let Some(end) = remaining[start..].find('>') else {
            kept.push_str(&remaining[start..]);
            return kept;
        };
        remaining = &remaining[start + end + 1..];
    }
}

/// The interactive session a Codex rollout records, `None` for a oneshot.
fn codex_session(path: &Path, modified: SystemTime) -> Option<InteractiveSession> {
    CODEX_SESSIONS.get_or_parse(path, modified, |path| {
        InteractiveSession::of(&first_line(path)?)
    })
}

/// Where a Codex rollout's interactive session ran - how a change to it names
/// its project.
pub(super) fn codex_rollout_cwd(path: &Path) -> Option<String> {
    Some(codex_session(path, modified_time(path)?)?.cwd().to_string())
}

/// The summary Copilot titled a workspace's session with.
pub(super) fn copilot_workspace_summary(path: &Path) -> Option<String> {
    let workspace =
        COPILOT_WORKSPACES.get_or_parse(path, modified_time(path)?, copilot_workspace)?;
    workspace.summary
}

/// Where a Copilot workspace's session ran - how a change to it names its
/// project.
pub(super) fn copilot_workspace_cwd(path: &Path) -> Option<String> {
    let workspace =
        COPILOT_WORKSPACES.get_or_parse(path, modified_time(path)?, copilot_workspace)?;
    Some(workspace.cwd)
}

fn codex_conversations(project: &str) -> Vec<RecordedConversation> {
    let Some(home) = codex_home() else {
        return Vec::new();
    };
    let titles = codex_titles(&home.join(CODEX_SESSION_INDEX));
    newest(rollout_files(&home.join(CODEX_SESSIONS_DIRECTORY)))
        .filter_map(|(modified, path)| {
            let session_id = codex_session(&path, modified)?.id_in(project)?;
            Some(RecordedConversation {
                agent_id: ID_CODEX,
                title: titles.get(&session_id).cloned(),
                updated_at: milliseconds_since_unix_epoch(modified),
                resume_arguments: session_resume_arguments(ID_CODEX, session_id.clone())
                    .unwrap_or_default(),
                conversation_id: session_id,
            })
        })
        .collect()
}

/// Codex's thread names by session id; a later line renames an earlier one.
pub(super) fn codex_titles(index: &Path) -> HashMap<String, String> {
    let Ok(file) = File::open(index) else {
        return HashMap::new();
    };
    records(BufReader::new(file))
        .filter_map(|record| {
            Some((
                string_field(&record, "id")?,
                string_field(&record, "thread_name")?,
            ))
        })
        .collect()
}

/// The two fields of a Copilot `workspace.yaml` the list reads.
#[derive(Clone)]
struct CopilotWorkspace {
    cwd: String,
    summary: Option<String>,
}

fn copilot_workspace(path: &Path) -> Option<CopilotWorkspace> {
    let workspace = std::fs::read_to_string(path).ok()?;
    Some(CopilotWorkspace {
        cwd: yaml_value(&workspace, COPILOT_CWD_KEY)?,
        summary: yaml_value(&workspace, COPILOT_SUMMARY_KEY),
    })
}

fn copilot_conversations(project: &str) -> Vec<RecordedConversation> {
    let Some(Ok(entries)) = copilot_session_root().map(std::fs::read_dir) else {
        return Vec::new();
    };
    let workspaces = entries
        .flatten()
        .map(|entry| entry.path().join(COPILOT_WORKSPACE_FILE))
        .filter_map(|path| Some((modified_time(&path)?, path)))
        .collect();

    newest(workspaces)
        .filter_map(|(modified, path)| {
            let workspace = COPILOT_WORKSPACES.get_or_parse(&path, modified, copilot_workspace)?;
            if !same_path(&workspace.cwd, project) {
                return None;
            }

            Some(RecordedConversation {
                agent_id: ID_COPILOT,
                conversation_id: path.parent()?.file_name()?.to_str()?.to_string(),
                title: workspace.summary,
                updated_at: milliseconds_since_unix_epoch(modified),
                resume_arguments: Vec::new(),
            })
        })
        .collect()
}

/// A top-level scalar of Copilot's flat `workspace.yaml`, its quotes dropped.
/// A block scalar (a summary Copilot copied from a multi-line prompt) yields
/// its first line, a markdown heading's marks dropped.
fn yaml_value(yaml: &str, key: &str) -> Option<String> {
    let mut lines = yaml.lines();
    let value = lines.find_map(|line| line.strip_prefix(key))?.trim();
    let is_block_scalar = value.starts_with(YAML_BLOCK_SCALAR_INDICATORS);
    if is_block_scalar {
        return lines
            .take_while(|line| line.is_empty() || line.starts_with(char::is_whitespace))
            .map(|line| line.trim().trim_start_matches(MARKDOWN_HEADING_MARK).trim())
            .find(|line| !line.is_empty())
            .map(str::to_string);
    }

    let value = value.trim_matches('"');
    (!value.is_empty()).then(|| value.replace("\\\\", "\\"))
}

