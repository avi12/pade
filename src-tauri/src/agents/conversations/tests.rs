use super::{
    first_typed_prompt, transcript_title, user_turn, yaml_value, UserTurn, SYNTHETIC_RECORD_FLAGS,
};

fn scratch_transcript(name: &str, lines: &[&str]) -> std::path::PathBuf {
    let directory =
        std::env::temp_dir().join(format!("pade-conversations-{name}-{}", std::process::id()));
    std::fs::create_dir_all(&directory).expect("scratch");
    let path = directory.join("conversation.jsonl");
    std::fs::write(&path, lines.join("\n")).expect("write");
    path
}

const PROMPT: &str =
    r#"{"type":"user","entrypoint":"cli","message":{"role":"user","content":"fix the build"}}"#;

#[test]
fn a_rename_wins_over_the_generated_title() {
    let path = scratch_transcript(
        "rename",
        &[
            PROMPT,
            r#"{"type":"ai-title","aiTitle":"Build fix"}"#,
            r#"{"type":"custom-title","customTitle":"My build"}"#,
        ],
    );
    assert_eq!(transcript_title(&path).as_deref(), Some("My build"));
}

#[test]
fn an_untitled_transcript_falls_back_to_its_first_prompt() {
    let path = scratch_transcript("untitled", &[PROMPT]);
    assert_eq!(transcript_title(&path), None);
    assert_eq!(first_typed_prompt(&path).as_deref(), Some("fix the build"));
}

#[test]
fn a_headless_run_is_not_a_conversation() {
    let path = scratch_transcript(
        "headless",
        &[r#"{"type":"user","entrypoint":"sdk-cli","message":{"content":"name this"}}"#],
    );
    assert_eq!(first_typed_prompt(&path), None);
}

#[test]
fn copilot_workspace_values_lose_their_quotes_and_escapes() {
    let yaml = "id: 1\ncwd: C:\\work\\app\nsummary: \"chat C:\\\\work\\\\app\"\n";
    assert_eq!(yaml_value(yaml, "cwd:").as_deref(), Some(r"C:\work\app"));
    assert_eq!(
        yaml_value(yaml, "summary:").as_deref(),
        Some(r"chat C:\work\app")
    );
    assert_eq!(yaml_value(yaml, "branch:"), None);
}

#[test]
fn a_copilot_block_summary_yields_its_first_line() {
    let yaml = "id: 1\nsummary: |-\n  # Loop - Iteration 1\n\n  You are in a loop\nbranch: main\n";
    assert_eq!(
        yaml_value(yaml, "summary:").as_deref(),
        Some("Loop - Iteration 1")
    );
    assert_eq!(yaml_value("summary: >\nbranch: main\n", "summary:"), None);
}

fn turn(record: &str) -> Option<UserTurn> {
    user_turn(&serde_json::from_str(record).expect("record"))
}

fn user_record(content: &str) -> String {
    serde_json::json!({ "type": "user", "message": { "content": content } }).to_string()
}

fn typed(prompt: &str) -> UserTurn {
    UserTurn::Typed(prompt.to_string())
}

#[test]
fn a_flagged_record_is_claudes_own() {
    for flag in SYNTHETIC_RECORD_FLAGS {
        let record = format!(r#"{{"type":"user","{flag}":true,"message":{{"content":"hi"}}}}"#);
        assert_eq!(turn(&record), None, "{flag}");
    }
    assert_eq!(
        turn(r#"{"type":"user","isMeta":false,"message":{"content":"hi"}}"#),
        Some(typed("hi"))
    );
}

#[test]
fn a_record_starting_with_a_synthetic_marker_is_claudes_own() {
    for content in [
        "<local-command-caveat>Caveat: The messages below were generated by the user while running local commands.</local-command-caveat>",
        "<local-command-stdout>Set model to Sonnet</local-command-stdout>",
        "<local-command-stderr>failed</local-command-stderr>",
        "<command-message>init is analyzing</command-message>",
        "<bash-stdout>ok</bash-stdout><bash-stderr></bash-stderr>",
        "<bash-stderr>boom</bash-stderr>",
        "<task-notification>\n<task-id>1</task-id>\n</task-notification>",
        "<system-reminder>\nscratch workspace\n</system-reminder>",
        "<user-prompt-submit-hook>echo</user-prompt-submit-hook>",
        "[Request interrupted by user]",
        "[Request interrupted by user for tool use]",
        "Caveat: The messages below were generated by the user while running local commands. DO NOT respond",
        "This session is being continued from a previous conversation that ran out of context.",
    ] {
        assert_eq!(turn(&user_record(content)), None, "{content}");
    }
}

#[test]
fn a_tool_result_is_not_a_prompt() {
    let record = r#"{"type":"user","message":{"content":[{"type":"tool_result","tool_use_id":"t","content":"total 28"}]}}"#;
    assert_eq!(turn(record), None);
}

#[test]
fn an_interruption_in_a_part_list_is_not_a_prompt() {
    let record = r#"{"type":"user","message":{"content":[{"type":"text","text":"[Request interrupted by user]"}]}}"#;
    assert_eq!(turn(record), None);
}

#[test]
fn a_prompt_with_an_image_keeps_its_text() {
    let record = r#"{"type":"user","message":{"content":[{"type":"image","source":{}},{"type":"text","text":"fix [Image #1]"}]}}"#;
    assert_eq!(turn(record), Some(typed("fix [Image #1]")));
}

#[test]
fn a_paste_loses_its_wrapper() {
    let content = "\n\n<pasted_content id=\"fd84\">\nlearn SQL\n</pasted_content id=\"fd84\">\n";
    assert_eq!(turn(&user_record(content)), Some(typed("learn SQL")));
}

#[test]
fn a_slash_command_reads_as_typed() {
    let content = "<command-name>/model</command-name>\n            <command-message>model</command-message>\n            <command-args>claude-sonnet-5-5</command-args>";
    assert_eq!(
        turn(&user_record(content)),
        Some(UserTurn::Command("/model claude-sonnet-5-5".to_string()))
    );
    let bare = "<command-message>relaunch</command-message>\n<command-name>/relaunch</command-name>\n<command-args></command-args>";
    assert_eq!(
        turn(&user_record(bare)),
        Some(UserTurn::Command("/relaunch".to_string()))
    );
}

#[test]
fn a_shell_command_reads_as_typed() {
    assert_eq!(
        turn(&user_record("<bash-input>code .</bash-input>")),
        Some(UserTurn::Command("!code .".to_string()))
    );
}

#[test]
fn the_first_typed_prompt_skips_claudes_own_records() {
    let caveat = r#"{"type":"user","isMeta":true,"entrypoint":"cli","message":{"content":"<local-command-caveat>Caveat</local-command-caveat>"}}"#;
    let command =
        user_record("<command-name>/effort</command-name><command-args>xhigh</command-args>");
    let output = user_record("<local-command-stdout>Set effort level</local-command-stdout>");
    let path = scratch_transcript("synthetic", &[caveat, &command, &output, PROMPT]);
    assert_eq!(first_typed_prompt(&path).as_deref(), Some("fix the build"));
}

#[test]
fn a_transcript_with_only_commands_is_titled_by_the_first() {
    let caveat = r#"{"type":"user","isMeta":true,"entrypoint":"cli","message":{"content":"<local-command-caveat>Caveat</local-command-caveat>"}}"#;
    let model = user_record(
        "<command-name>/model</command-name><command-args>claude-opus-5-5</command-args>",
    );
    let effort =
        user_record("<command-name>/effort</command-name><command-args>low</command-args>");
    let path = scratch_transcript("commands", &[caveat, &model, &effort]);
    assert_eq!(
        first_typed_prompt(&path).as_deref(),
        Some("/model claude-opus-5-5")
    );
}

#[test]
fn a_transcript_with_nothing_typed_is_not_a_conversation() {
    let notice = user_record("<task-notification>done</task-notification>");
    let path = scratch_transcript("nothing-typed", &[&notice]);
    assert_eq!(first_typed_prompt(&path), None);
}
